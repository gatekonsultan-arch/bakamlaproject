-- =====================================================================
-- Skema Database Aplikasi Absensi Geotagging (Oracle Database 23ai/19c)
-- Jalankan sebagai user aplikasi (mis. ABSENSI), BUKAN sebagai SYS.
-- Setiap statement diakhiri ";" di akhir baris (dibaca oleh scripts/migrate.js)
-- =====================================================================

CREATE TABLE roles (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR2(30)  NOT NULL,
  name        VARCHAR2(60)  NOT NULL,
  CONSTRAINT uq_roles_code UNIQUE (code)
);

CREATE TABLE sites (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(120) NOT NULL,
  address     VARCHAR2(255),
  latitude    NUMBER(10,7)  NOT NULL,
  longitude   NUMBER(10,7)  NOT NULL,
  radius_m    NUMBER(6)     DEFAULT 100 NOT NULL,
  is_active   NUMBER(1)     DEFAULT 1 NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_sites_active CHECK (is_active IN (0,1)),
  CONSTRAINT ck_sites_lat    CHECK (latitude BETWEEN -90 AND 90),
  CONSTRAINT ck_sites_lng    CHECK (longitude BETWEEN -180 AND 180),
  CONSTRAINT ck_sites_radius CHECK (radius_m BETWEEN 10 AND 50000)
);

CREATE TABLE users (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username       VARCHAR2(50)  NOT NULL,
  full_name      VARCHAR2(120) NOT NULL,
  email          VARCHAR2(120),
  phone          VARCHAR2(30),
  password_hash  VARCHAR2(100) NOT NULL,
  role_id        NUMBER        NOT NULL,
  site_id        NUMBER,
  is_active      NUMBER(1)     DEFAULT 1 NOT NULL,
  failed_logins  NUMBER(3)     DEFAULT 0 NOT NULL,
  locked_until   TIMESTAMP WITH TIME ZONE,
  token_version  NUMBER(10)    DEFAULT 0 NOT NULL,
  last_login_at  TIMESTAMP WITH TIME ZONE,
  created_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id),
  CONSTRAINT fk_users_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT ck_users_active CHECK (is_active IN (0,1))
);

CREATE INDEX ix_users_role ON users(role_id);

CREATE INDEX ix_users_site ON users(site_id);

-- Satu baris per user per hari: berisi check-in dan check-out.
CREATE TABLE attendance (
  id                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id               NUMBER        NOT NULL,
  site_id               NUMBER        NOT NULL,
  att_date              DATE          NOT NULL,
  check_in_at           TIMESTAMP WITH TIME ZONE NOT NULL,
  check_in_lat          NUMBER(10,7)  NOT NULL,
  check_in_lng          NUMBER(10,7)  NOT NULL,
  check_in_accuracy     NUMBER(8,2),
  check_in_distance_m   NUMBER(10,2)  NOT NULL,
  check_out_at          TIMESTAMP WITH TIME ZONE,
  check_out_lat         NUMBER(10,7),
  check_out_lng         NUMBER(10,7),
  check_out_accuracy    NUMBER(8,2),
  check_out_distance_m  NUMBER(10,2),
  note                  VARCHAR2(255),
  device_info           VARCHAR2(255),
  ip_address            VARCHAR2(45),
  created_at            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_att_user_date UNIQUE (user_id, att_date),
  CONSTRAINT fk_att_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_att_site FOREIGN KEY (site_id) REFERENCES sites(id)
);

CREATE INDEX ix_att_date ON attendance(att_date);

CREATE INDEX ix_att_site_date ON attendance(site_id, att_date);

CREATE TABLE audit_log (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     NUMBER,
  action      VARCHAR2(50)   NOT NULL,
  detail      VARCHAR2(1000),
  ip_address  VARCHAR2(45),
  created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_audit_created ON audit_log(created_at);
