UPDATE purchase_request_items SET item_status = 'APPROVED'
 WHERE item_status = 'PENDING' AND request_id IN (SELECT id FROM purchase_requests WHERE status IN ('APPROVED','ORDERED','PARTIAL','RECEIVED'));
UPDATE purchase_request_items SET item_status = 'REJECTED'
 WHERE item_status = 'PENDING' AND request_id IN (SELECT id FROM purchase_requests WHERE status = 'REJECTED');

CREATE TABLE atp_documents (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id          NUMBER        NOT NULL,
  doc_no           VARCHAR2(60)  NOT NULL,
  work_area        VARCHAR2(200) NOT NULL,
  inspection_date  DATE          NOT NULL,
  status           VARCHAR2(10)  DEFAULT 'DRAFT' NOT NULL,
  notes            VARCHAR2(1000),
  created_by       NUMBER        NOT NULL,
  created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  submitted_by     NUMBER,
  submitted_at     TIMESTAMP WITH TIME ZONE,
  submitted_sig    VARCHAR2(100),
  approved_by      NUMBER,
  approved_at      TIMESTAMP WITH TIME ZONE,
  approved_sig     VARCHAR2(100),
  revision_note    VARCHAR2(1000),
  CONSTRAINT uq_atp_no UNIQUE (doc_no),
  CONSTRAINT fk_atp_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT fk_atp_created FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_atp_sub FOREIGN KEY (submitted_by) REFERENCES users(id),
  CONSTRAINT fk_atp_appr FOREIGN KEY (approved_by) REFERENCES users(id),
  CONSTRAINT ck_atp_status CHECK (status IN ('DRAFT','SUBMITTED','APPROVED','REVISION'))
);

CREATE INDEX ix_atp_site_status ON atp_documents(site_id, status);

CREATE TABLE atp_items (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  atp_id       NUMBER        NOT NULL,
  section      VARCHAR2(1)   NOT NULL,
  seq          NUMBER(4)     NOT NULL,
  description  VARCHAR2(200) NOT NULL,
  unit         VARCHAR2(20),
  planned      VARCHAR2(60),
  actual       VARCHAR2(60),
  tolerance    VARCHAR2(60),
  result       VARCHAR2(7),
  remarks      VARCHAR2(500),
  photo_file   VARCHAR2(100),
  CONSTRAINT fk_atpi_doc FOREIGN KEY (atp_id) REFERENCES atp_documents(id),
  CONSTRAINT ck_atpi_section CHECK (section IN ('A','B','C','D','E','F')),
  CONSTRAINT ck_atpi_result CHECK (result IN ('APPROVE','REJECT'))
);

CREATE INDEX ix_atpi_doc ON atp_items(atp_id, section, seq);
