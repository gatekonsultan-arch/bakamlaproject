-- =====================================================================
-- Modul Kontrol Material Logistik
-- Alur: PM/SM input kebutuhan -> Logistik ajukan pembelian -> PM approve
--       -> Logistik catat pemesanan -> catat penerimaan -> catat pemakaian
-- =====================================================================

-- Master material (katalog)
CREATE TABLE materials (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR2(40)  NOT NULL,
  name        VARCHAR2(150) NOT NULL,
  unit        VARCHAR2(20)  NOT NULL,
  category    VARCHAR2(60),
  is_active   NUMBER(1) DEFAULT 1 NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_materials_code UNIQUE (code),
  CONSTRAINT ck_materials_active CHECK (is_active IN (0,1))
);

-- Kebutuhan material per lokasi (diinput Project Manager / Site Manager)
-- planned_qty : total kebutuhan sesuai rencana (batas "melebihi rencana")
-- min_stock   : stok minimum di lokasi (batas "stok menipis")
-- warn_pct    : persentase "mendekati" ambang batas (default 80%)
CREATE TABLE site_materials (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id      NUMBER        NOT NULL,
  material_id  NUMBER        NOT NULL,
  planned_qty  NUMBER(14,3)  NOT NULL,
  min_stock    NUMBER(14,3)  DEFAULT 0 NOT NULL,
  warn_pct     NUMBER(3)     DEFAULT 80 NOT NULL,
  notes        VARCHAR2(500),
  created_by   NUMBER        NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_by   NUMBER,
  updated_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_site_materials UNIQUE (site_id, material_id),
  CONSTRAINT fk_sm_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT fk_sm_material FOREIGN KEY (material_id) REFERENCES materials(id),
  CONSTRAINT fk_sm_created FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT ck_sm_planned CHECK (planned_qty > 0),
  CONSTRAINT ck_sm_min CHECK (min_stock >= 0),
  CONSTRAINT ck_sm_warn CHECK (warn_pct BETWEEN 1 AND 99)
);

-- Permintaan pembelian (Purchase Request)
-- Status: PENDING -> APPROVED / REJECTED -> ORDERED -> PARTIAL / RECEIVED ; CANCELLED
CREATE TABLE purchase_requests (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_no     VARCHAR2(40)  NOT NULL,
  site_id        NUMBER        NOT NULL,
  status         VARCHAR2(20)  DEFAULT 'PENDING' NOT NULL,
  needed_date    DATE,
  note           VARCHAR2(500),
  requested_by   NUMBER        NOT NULL,
  requested_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  decided_by     NUMBER,
  decided_at     TIMESTAMP WITH TIME ZONE,
  decision_note  VARCHAR2(500),
  supplier       VARCHAR2(150),
  po_number      VARCHAR2(60),
  order_date     DATE,
  expected_date  DATE,
  ordered_by     NUMBER,
  ordered_at     TIMESTAMP WITH TIME ZONE,
  CONSTRAINT uq_pr_no UNIQUE (request_no),
  CONSTRAINT fk_pr_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT fk_pr_req FOREIGN KEY (requested_by) REFERENCES users(id),
  CONSTRAINT fk_pr_dec FOREIGN KEY (decided_by) REFERENCES users(id),
  CONSTRAINT fk_pr_ord FOREIGN KEY (ordered_by) REFERENCES users(id),
  CONSTRAINT ck_pr_status CHECK (status IN ('PENDING','APPROVED','REJECTED','ORDERED','PARTIAL','RECEIVED','CANCELLED'))
);

CREATE INDEX ix_pr_site_status ON purchase_requests(site_id, status);

CREATE TABLE purchase_request_items (
  id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id        NUMBER        NOT NULL,
  site_material_id  NUMBER        NOT NULL,
  qty               NUMBER(14,3)  NOT NULL,
  qty_received      NUMBER(14,3)  DEFAULT 0 NOT NULL,
  unit_price        NUMBER(16,2),
  note              VARCHAR2(255),
  CONSTRAINT fk_pri_pr FOREIGN KEY (request_id) REFERENCES purchase_requests(id),
  CONSTRAINT fk_pri_sm FOREIGN KEY (site_material_id) REFERENCES site_materials(id),
  CONSTRAINT ck_pri_qty CHECK (qty > 0),
  CONSTRAINT ck_pri_recv CHECK (qty_received >= 0)
);

CREATE INDEX ix_pri_request ON purchase_request_items(request_id);

CREATE INDEX ix_pri_sm ON purchase_request_items(site_material_id);

-- Pencatatan keluar-masuk stok
-- IN  = penerimaan barang (biasanya dari PR), OUT = pemakaian, ADJ = penyesuaian stok opname (+/-)
CREATE TABLE stock_movements (
  id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_material_id  NUMBER        NOT NULL,
  movement_type     VARCHAR2(3)   NOT NULL,
  qty               NUMBER(14,3)  NOT NULL,
  movement_date     DATE          NOT NULL,
  pr_item_id        NUMBER,
  reference         VARCHAR2(100),
  note              VARCHAR2(500),
  created_by        NUMBER        NOT NULL,
  created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_mv_sm FOREIGN KEY (site_material_id) REFERENCES site_materials(id),
  CONSTRAINT fk_mv_pri FOREIGN KEY (pr_item_id) REFERENCES purchase_request_items(id),
  CONSTRAINT fk_mv_user FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT ck_mv_type CHECK (movement_type IN ('IN','OUT','ADJ')),
  CONSTRAINT ck_mv_qty CHECK ((movement_type IN ('IN','OUT') AND qty > 0) OR (movement_type = 'ADJ' AND qty <> 0))
);

CREATE INDEX ix_mv_sm_date ON stock_movements(site_material_id, movement_date);
