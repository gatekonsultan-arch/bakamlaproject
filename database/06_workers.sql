-- =====================================================================
-- Modul Tenaga Kerja Harian (tukang, mandor, buruh) & Rekap Upah Mingguan
-- Alur: Site Manager absen harian di lokasi (geotag) -> rekap Senin-Sabtu
--       -> Site Manager ajukan -> Project Manager setujui (terkunci) -> dibayar
-- =====================================================================

CREATE TABLE workers (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id        NUMBER        NOT NULL,
  name           VARCHAR2(120) NOT NULL,
  category       VARCHAR2(10)  NOT NULL,
  trade          VARCHAR2(60),
  nik            VARCHAR2(20),
  phone          VARCHAR2(30),
  daily_rate     NUMBER(12,2)  NOT NULL,
  overtime_rate  NUMBER(12,2)  DEFAULT 0 NOT NULL,
  is_active      NUMBER(1)     DEFAULT 1 NOT NULL,
  created_by     NUMBER        NOT NULL,
  created_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_wk_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT fk_wk_user FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT ck_wk_cat CHECK (category IN ('MANDOR','TUKANG','BURUH')),
  CONSTRAINT ck_wk_rate CHECK (daily_rate >= 0 AND overtime_rate >= 0),
  CONSTRAINT ck_wk_active CHECK (is_active IN (0,1))
);

CREATE INDEX ix_wk_site ON workers(site_id, is_active);

-- Absensi harian per pekerja. Upah & tarif lembur disalin saat dicatat,
-- sehingga perubahan upah di kemudian hari tidak mengubah hari yang sudah lewat.
CREATE TABLE worker_attendance (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  worker_id       NUMBER        NOT NULL,
  site_id         NUMBER        NOT NULL,
  work_date       DATE          NOT NULL,
  status          VARCHAR2(6)   NOT NULL,
  overtime_hours  NUMBER(4,1)   DEFAULT 0 NOT NULL,
  day_rate        NUMBER(12,2)  NOT NULL,
  ot_rate         NUMBER(12,2)  NOT NULL,
  note            VARCHAR2(255),
  recorded_by     NUMBER        NOT NULL,
  recorded_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_wa_worker_date UNIQUE (worker_id, work_date),
  CONSTRAINT fk_wa_worker FOREIGN KEY (worker_id) REFERENCES workers(id),
  CONSTRAINT fk_wa_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT fk_wa_user FOREIGN KEY (recorded_by) REFERENCES users(id),
  CONSTRAINT ck_wa_status CHECK (status IN ('FULL','HALF','ABSENT')),
  CONSTRAINT ck_wa_ot CHECK (overtime_hours BETWEEN 0 AND 12)
);

CREATE INDEX ix_wa_site_date ON worker_attendance(site_id, work_date);

-- Bukti pengisian per lokasi per hari: posisi pengabsen + foto apel (opsional)
CREATE TABLE worker_day_sheets (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id      NUMBER        NOT NULL,
  work_date    DATE          NOT NULL,
  latitude     NUMBER(10,7)  NOT NULL,
  longitude    NUMBER(10,7)  NOT NULL,
  accuracy     NUMBER(8,2),
  distance_m   NUMBER(10,2)  NOT NULL,
  photo_file   VARCHAR2(100),
  recorded_by  NUMBER        NOT NULL,
  updated_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_wds UNIQUE (site_id, work_date),
  CONSTRAINT fk_wds_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT fk_wds_user FOREIGN KEY (recorded_by) REFERENCES users(id)
);

-- Kasbon: dipotong dari upah pada pekan tanggal kasbon
CREATE TABLE worker_advances (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  worker_id    NUMBER        NOT NULL,
  site_id      NUMBER        NOT NULL,
  adv_date     DATE          NOT NULL,
  amount       NUMBER(12,2)  NOT NULL,
  note         VARCHAR2(255),
  recorded_by  NUMBER        NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_adv_worker FOREIGN KEY (worker_id) REFERENCES workers(id),
  CONSTRAINT fk_adv_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT fk_adv_user FOREIGN KEY (recorded_by) REFERENCES users(id),
  CONSTRAINT ck_adv_amount CHECK (amount > 0)
);

CREATE INDEX ix_adv_site_date ON worker_advances(site_id, adv_date);

-- Rekap upah mingguan (Senin-Sabtu). Status: SUBMITTED -> APPROVED -> PAID ; RETURNED.
-- Saat disetujui, rincian disimpan (snapshot) agar angka tidak berubah lagi.
CREATE TABLE payroll_weeks (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id        NUMBER        NOT NULL,
  week_start     DATE          NOT NULL,
  status         VARCHAR2(10)  NOT NULL,
  total_amount   NUMBER(14,2),
  snapshot       CLOB,
  submitted_by   NUMBER,
  submitted_at   TIMESTAMP WITH TIME ZONE,
  submitted_sig  VARCHAR2(100),
  approved_by    NUMBER,
  approved_at    TIMESTAMP WITH TIME ZONE,
  approved_sig   VARCHAR2(100),
  paid_by        NUMBER,
  paid_at        TIMESTAMP WITH TIME ZONE,
  return_note    VARCHAR2(500),
  CONSTRAINT uq_pw UNIQUE (site_id, week_start),
  CONSTRAINT fk_pw_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT ck_pw_status CHECK (status IN ('SUBMITTED','APPROVED','PAID','RETURNED')),
  CONSTRAINT ck_pw_snap CHECK (snapshot IS JSON)
);
