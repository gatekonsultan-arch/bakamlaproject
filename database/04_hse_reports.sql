-- =====================================================================
-- Modul Laporan Harian K3 (Daily Work Report)
-- Alur: HSE Officer menyusun (DRAFT) -> kirim (SUBMITTED)
--       -> Site Manager/PIC Site mengetahui (ACKNOWLEDGED)
--       -> HSE Manager menyetujui (APPROVED). Bisa dikembalikan (REVISION).
-- =====================================================================

-- Pengaturan laporan per lokasi (kop, proyek, tim, APD) dalam bentuk JSON
CREATE TABLE site_report_settings (
  site_id     NUMBER PRIMARY KEY,
  settings    CLOB NOT NULL,
  updated_by  NUMBER,
  updated_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_srs_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT ck_srs_json CHECK (settings IS JSON)
);

CREATE TABLE hse_reports (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id          NUMBER        NOT NULL,
  report_date      DATE          NOT NULL,
  report_no        VARCHAR2(80)  NOT NULL,
  status           VARCHAR2(20)  DEFAULT 'DRAFT' NOT NULL,
  start_time       VARCHAR2(5)   DEFAULT '08:00' NOT NULL,
  finish_time      VARCHAR2(5)   DEFAULT '17:00' NOT NULL,
  category         VARCHAR2(200),
  subject          VARCHAR2(300),
  content          CLOB          NOT NULL,
  created_by       NUMBER        NOT NULL,
  created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  submitted_by     NUMBER,
  submitted_at     TIMESTAMP WITH TIME ZONE,
  acknowledged_by  NUMBER,
  acknowledged_at  TIMESTAMP WITH TIME ZONE,
  approved_by      NUMBER,
  approved_at      TIMESTAMP WITH TIME ZONE,
  revision_note    VARCHAR2(1000),
  CONSTRAINT uq_hse_site_date UNIQUE (site_id, report_date),
  CONSTRAINT fk_hse_site FOREIGN KEY (site_id) REFERENCES sites(id),
  CONSTRAINT fk_hse_created FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_hse_sub FOREIGN KEY (submitted_by) REFERENCES users(id),
  CONSTRAINT fk_hse_ack FOREIGN KEY (acknowledged_by) REFERENCES users(id),
  CONSTRAINT fk_hse_appr FOREIGN KEY (approved_by) REFERENCES users(id),
  CONSTRAINT ck_hse_status CHECK (status IN ('DRAFT','SUBMITTED','ACKNOWLEDGED','APPROVED','REVISION')),
  CONSTRAINT ck_hse_content CHECK (content IS JSON)
);

CREATE INDEX ix_hse_status ON hse_reports(status);

CREATE TABLE hse_report_photos (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id    NUMBER        NOT NULL,
  file_name    VARCHAR2(100) NOT NULL,
  original     VARCHAR2(255),
  taken_time   VARCHAR2(5),
  activity_key VARCHAR2(30)  DEFAULT 'custom' NOT NULL,
  caption      VARCHAR2(120),
  sky          VARCHAR2(1),
  included     NUMBER(1) DEFAULT 1 NOT NULL,
  sort_order   NUMBER(5) DEFAULT 0 NOT NULL,
  uploaded_by  NUMBER        NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_hp_report FOREIGN KEY (report_id) REFERENCES hse_reports(id),
  CONSTRAINT fk_hp_user FOREIGN KEY (uploaded_by) REFERENCES users(id),
  CONSTRAINT ck_hp_inc CHECK (included IN (0,1))
);

CREATE INDEX ix_hp_report ON hse_report_photos(report_id);

